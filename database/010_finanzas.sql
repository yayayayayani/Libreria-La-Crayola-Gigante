CREATE TABLE movimientos_financieros (
 id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
 id_compra BIGINT REFERENCES compras(id_compra),
 clave VARCHAR(64) NOT NULL UNIQUE,
 tipo VARCHAR(12) NOT NULL CHECK(tipo IN ('INGRESO','EGRESO','APERTURA')),
 categoria VARCHAR(20) NOT NULL CHECK(categoria IN ('OTRO_INGRESO','GASTO','RETIRO','COMPRA','SALDO_INICIAL')),
 metodo VARCHAR(20) NOT NULL CHECK(metodo IN ('EFECTIVO','TARJETA','TRANSFERENCIA')),
 monto NUMERIC(12,2) NOT NULL CHECK(monto>0),
 fecha DATE NOT NULL,
 concepto VARCHAR(250) NOT NULL,
 referencia VARCHAR(100),
 creado_en TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
 anulado_en TIMESTAMP,
 motivo_anulacion VARCHAR(250)
);
CREATE INDEX ix_finanzas_fecha ON movimientos_financieros(fecha);
CREATE UNIQUE INDEX ix_finanzas_apertura ON movimientos_financieros(metodo) WHERE tipo='APERTURA' AND anulado_en IS NULL;
