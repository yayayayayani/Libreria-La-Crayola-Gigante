CREATE TABLE pedidos (
 id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cliente BIGINT NOT NULL REFERENCES clientes(id_cliente),
 id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
 clave VARCHAR(64) NOT NULL UNIQUE,
 estado VARCHAR(24) NOT NULL CHECK(estado IN ('APROBADO','PENDIENTE_APROBACION','RECHAZADO','CANCELADO','VENDIDO','PAGADO')),
 subtotal NUMERIC(12,2) NOT NULL CHECK(subtotal>0),
 descuento NUMERIC(5,2) NOT NULL CHECK(descuento BETWEEN 0 AND 50),
 total NUMERIC(12,2) NOT NULL CHECK(total>0),
 fecha TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE TABLE detalle_pedidos (
 id_pedido BIGINT NOT NULL REFERENCES pedidos(id_pedido),
 id_producto BIGINT NOT NULL REFERENCES productos(id_producto),
 cantidad INTEGER NOT NULL CHECK(cantidad>0),
 precio NUMERIC(12,2) NOT NULL CHECK(precio>=0),
 PRIMARY KEY(id_pedido,id_producto)
);
CREATE TABLE aprobaciones (
 id_pedido BIGINT PRIMARY KEY REFERENCES pedidos(id_pedido),
 id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
 decision VARCHAR(12) NOT NULL CHECK(decision IN ('APROBADO','RECHAZADO')),
 motivo VARCHAR(500) NOT NULL,
 fecha TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);
ALTER TABLE ventas ADD id_pedido BIGINT UNIQUE REFERENCES pedidos(id_pedido);
CREATE TABLE pagos (
 id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_venta BIGINT NOT NULL REFERENCES ventas(id_venta),
 id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
 clave VARCHAR(64) NOT NULL UNIQUE,
 monto NUMERIC(12,2) NOT NULL CHECK(monto>0),
 metodo VARCHAR(20) NOT NULL CHECK(metodo IN ('EFECTIVO','TARJETA','TRANSFERENCIA')),
 referencia VARCHAR(100),
 fecha TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX ix_pedidos_fecha_estado ON pedidos(fecha,estado);
CREATE INDEX ix_pagos_venta ON pagos(id_venta);
