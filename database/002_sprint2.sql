CREATE TABLE proveedores (
 id_proveedor NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR2(150 CHAR) NOT NULL,
 nit VARCHAR2(20 CHAR) NOT NULL UNIQUE,
 correo VARCHAR2(120 CHAR), telefono VARCHAR2(25 CHAR), direccion VARCHAR2(250 CHAR),
 estado CHAR(1) DEFAULT 'A' NOT NULL CHECK (estado IN ('A','I'))
);
CREATE TABLE compras (
 id_compra NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_proveedor NUMBER NOT NULL REFERENCES proveedores(id_proveedor),
 id_usuario NUMBER NOT NULL REFERENCES usuarios(id_usuario),
 factura VARCHAR2(80 CHAR) NOT NULL,
 clave VARCHAR2(64 CHAR) NOT NULL UNIQUE,
 total NUMBER(12,2) NOT NULL CHECK (total > 0),
 estado VARCHAR2(12 CHAR) DEFAULT 'RECIBIDA' NOT NULL CHECK (estado = 'RECIBIDA'),
 fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT uq_compra_factura UNIQUE (id_proveedor, factura)
);
CREATE TABLE detalle_compras (
 id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_compra NUMBER NOT NULL REFERENCES compras(id_compra),
 id_producto NUMBER NOT NULL REFERENCES productos(id_producto),
 cantidad NUMBER(10) NOT NULL CHECK (cantidad > 0),
 costo NUMBER(12,2) NOT NULL CHECK (costo > 0),
 CONSTRAINT uq_detalle_producto UNIQUE (id_compra,id_producto)
);
CREATE TABLE recepciones (
 id_recepcion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_compra NUMBER NOT NULL UNIQUE REFERENCES compras(id_compra),
 id_usuario NUMBER NOT NULL REFERENCES usuarios(id_usuario),
 fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE movimientos_inventario (
 id_movimiento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_producto NUMBER NOT NULL REFERENCES productos(id_producto),
 id_recepcion NUMBER REFERENCES recepciones(id_recepcion),
 id_usuario NUMBER REFERENCES usuarios(id_usuario),
 tipo VARCHAR2(15 CHAR) NOT NULL CHECK (tipo IN ('APERTURA','ENTRADA_COMPRA')),
 cantidad NUMBER(10) NOT NULL CHECK (cantidad >= 0),
 stock_anterior NUMBER(10) NOT NULL CHECK (stock_anterior >= 0),
 stock_nuevo NUMBER(10) NOT NULL CHECK (stock_nuevo >= 0),
 fecha TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT ck_mov_saldo CHECK (stock_nuevo = stock_anterior + cantidad),
 CONSTRAINT uq_mov_recepcion UNIQUE (id_recepcion,id_producto)
);
CREATE INDEX ix_mov_producto ON movimientos_inventario(id_producto,fecha);
CREATE TABLE correos_pendientes (
 id_correo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 destinatario VARCHAR2(120 CHAR) NOT NULL,
 asunto VARCHAR2(200 CHAR) NOT NULL,
 mensaje VARCHAR2(2000 CHAR) NOT NULL,
 estado VARCHAR2(12 CHAR) DEFAULT 'PENDIENTE' NOT NULL CHECK (estado IN ('PENDIENTE','ENVIADO')),
 intentos NUMBER DEFAULT 0 NOT NULL,
 creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 enviado_en TIMESTAMP,
 ultimo_error VARCHAR2(100 CHAR)
);
