-- Esquema PostgreSQL de Sprints 1 y 2. Sin datos iniciales: se copian de Oracle.
-- Ejecutar mediante migrarNeon.js en una transacción y destino vacío.
CREATE TABLE roles (
 id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(50) NOT NULL UNIQUE, descripcion VARCHAR(250),
 estado CHAR(1) DEFAULT 'A' NOT NULL CHECK (estado IN ('A','I'))
);
CREATE TABLE permisos (
 id_permiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(80) NOT NULL UNIQUE, descripcion VARCHAR(250) NOT NULL
);
CREATE TABLE rol_permiso (
 id_rol BIGINT NOT NULL REFERENCES roles(id_rol),
 id_permiso BIGINT NOT NULL REFERENCES permisos(id_permiso),
 PRIMARY KEY(id_rol,id_permiso)
);
CREATE TABLE usuarios (
 id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre_completo VARCHAR(120) NOT NULL, nombre_usuario VARCHAR(50) NOT NULL UNIQUE,
 contrasena_hash VARCHAR(255) NOT NULL, id_rol BIGINT NOT NULL REFERENCES roles(id_rol),
 estado CHAR(1) DEFAULT 'A' NOT NULL CHECK (estado IN ('A','I')),
 creado_en TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL, correo VARCHAR(120)
);
CREATE UNIQUE INDEX uq_usuario_correo ON usuarios(LOWER(TRIM(correo)));
CREATE TABLE clientes (
 id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombres VARCHAR(100) NOT NULL, apellidos VARCHAR(100), nit VARCHAR(20) UNIQUE,
 telefono VARCHAR(25), correo VARCHAR(120), direccion VARCHAR(250),
 estado CHAR(1) DEFAULT 'A' NOT NULL CHECK (estado IN ('A','I')),
 creado_en TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX uq_cliente_correo ON clientes(LOWER(TRIM(correo)));
CREATE TABLE categorias (
 id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE, descripcion VARCHAR(250),
 estado CHAR(1) DEFAULT 'A' NOT NULL CHECK (estado IN ('A','I'))
);
CREATE TABLE productos (
 id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(50) NOT NULL UNIQUE, nombre VARCHAR(150) NOT NULL, descripcion VARCHAR(500),
 precio NUMERIC(12,2) NOT NULL CHECK (precio>=0),
 stock BIGINT DEFAULT 0 NOT NULL CHECK(stock BETWEEN 0 AND 9999999999),
 id_categoria BIGINT NOT NULL REFERENCES categorias(id_categoria),
 estado CHAR(1) DEFAULT 'A' NOT NULL CHECK (estado IN ('A','I')),
 creado_en TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
 stock_minimo BIGINT DEFAULT 0 NOT NULL CHECK(stock_minimo BETWEEN 0 AND 9999999999)
);
CREATE TABLE bitacora (
 id_bitacora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuario BIGINT REFERENCES usuarios(id_usuario), accion VARCHAR(80) NOT NULL,
 tabla_afectada VARCHAR(50) NOT NULL, id_registro_afectado BIGINT,
 detalle VARCHAR(1000), fecha_hora TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE TABLE proveedores (
 id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(150) NOT NULL, nit VARCHAR(20) NOT NULL UNIQUE,
 correo VARCHAR(120), telefono VARCHAR(25), direccion VARCHAR(250),
 estado CHAR(1) DEFAULT 'A' NOT NULL CHECK(estado IN ('A','I'))
);
CREATE TABLE compras (
 id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_proveedor BIGINT NOT NULL REFERENCES proveedores(id_proveedor),
 id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
 factura VARCHAR(80) NOT NULL, clave VARCHAR(64) NOT NULL UNIQUE,
 total NUMERIC(12,2) NOT NULL CHECK(total>0),
 estado VARCHAR(12) DEFAULT 'RECIBIDA' NOT NULL CHECK(estado='RECIBIDA'),
 fecha TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
 CONSTRAINT uq_compra_factura UNIQUE(id_proveedor,factura)
);
CREATE TABLE detalle_compras (
 id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_compra BIGINT NOT NULL REFERENCES compras(id_compra),
 id_producto BIGINT NOT NULL REFERENCES productos(id_producto),
 cantidad BIGINT NOT NULL CHECK(cantidad BETWEEN 1 AND 9999999999),
 costo NUMERIC(12,2) NOT NULL CHECK(costo>0),
 CONSTRAINT uq_detalle_producto UNIQUE(id_compra,id_producto)
);
CREATE TABLE recepciones (
 id_recepcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_compra BIGINT NOT NULL UNIQUE REFERENCES compras(id_compra),
 id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
 fecha TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE TABLE movimientos_inventario (
 id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_producto BIGINT NOT NULL REFERENCES productos(id_producto),
 id_recepcion BIGINT REFERENCES recepciones(id_recepcion), id_usuario BIGINT REFERENCES usuarios(id_usuario),
 tipo VARCHAR(15) NOT NULL CHECK(tipo IN ('APERTURA','ENTRADA_COMPRA')),
 cantidad BIGINT NOT NULL CHECK(cantidad BETWEEN 0 AND 9999999999),
 stock_anterior BIGINT NOT NULL CHECK(stock_anterior BETWEEN 0 AND 9999999999),
 stock_nuevo BIGINT NOT NULL CHECK(stock_nuevo BETWEEN 0 AND 9999999999),
 fecha TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
 CONSTRAINT ck_mov_saldo CHECK(stock_nuevo=stock_anterior+cantidad),
 CONSTRAINT uq_mov_recepcion UNIQUE(id_recepcion,id_producto)
);
CREATE TABLE correos_pendientes (
 id_correo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 destinatario VARCHAR(120) NOT NULL, asunto VARCHAR(200) NOT NULL, mensaje VARCHAR(2000) NOT NULL,
 estado VARCHAR(12) DEFAULT 'PENDIENTE' NOT NULL CHECK(estado IN ('PENDIENTE','ENVIADO')),
 intentos BIGINT DEFAULT 0 NOT NULL CHECK(intentos>=0),
 creado_en TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL, enviado_en TIMESTAMP(6), ultimo_error VARCHAR(100)
);
CREATE TABLE migraciones (nombre VARCHAR(100) PRIMARY KEY, aplicado_en TIMESTAMP(6) DEFAULT LOCALTIMESTAMP);
CREATE INDEX ix_usuarios_rol ON usuarios(id_rol);
CREATE INDEX ix_rp_permiso ON rol_permiso(id_permiso);
CREATE INDEX ix_productos_categoria ON productos(id_categoria);
CREATE INDEX ix_bitacora_usuario_fecha ON bitacora(id_usuario,fecha_hora);
CREATE INDEX ix_bitacora_fecha ON bitacora(fecha_hora);
CREATE INDEX ix_mov_producto ON movimientos_inventario(id_producto,fecha);
