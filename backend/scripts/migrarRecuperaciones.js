require("dotenv").config({ quiet: true });
const driver = require("../src/config/driver");
const { conectar, filas } = require("../src/services/db");
async function main() {
  const c = await conectar();
  const pg = driver.motor() === "postgres";
  try {
    if (pg) await c.execute("SELECT pg_advisory_xact_lock(606009)");
    if ((await filas(c, "SELECT nombre FROM migraciones WHERE nombre='009_recuperaciones'")).length) return;
    const id = pg ? "BIGINT GENERATED BY DEFAULT AS IDENTITY" : "NUMBER GENERATED BY DEFAULT AS IDENTITY";
    const num = pg ? "BIGINT" : "NUMBER(10)";
    const str = (n) => pg ? `VARCHAR(${n})` : `VARCHAR2(${n} CHAR)`;
    const existe = await filas(c, pg
      ? "SELECT table_name FROM information_schema.tables WHERE table_schema=current_schema() AND table_name='recuperaciones_compra'"
      : "SELECT table_name FROM user_tables WHERE table_name='RECUPERACIONES_COMPRA'");
    if (!existe.length) await c.execute(`CREATE TABLE recuperaciones_compra (
      id_recuperacion ${id} PRIMARY KEY,
      id_compra ${num} NOT NULL REFERENCES compras(id_compra),
      id_usuario ${num} NOT NULL REFERENCES usuarios(id_usuario),
      tipo ${str(20)} NOT NULL CHECK(tipo IN ('NOTA_CREDITO','REEMBOLSO','PERDIDA')),
      monto DECIMAL(12,2) NOT NULL CHECK(monto>0),
      referencia ${str(100)} NOT NULL,
      fecha_documento ${str(10)} NOT NULL,
      observaciones ${str(500)},
      clave ${str(64)} NOT NULL UNIQUE,
      creado_en TIMESTAMP DEFAULT ${pg ? "LOCALTIMESTAMP" : "SYSTIMESTAMP"} NOT NULL,
      CONSTRAINT uq_recup_documento UNIQUE(id_compra,tipo,referencia)
    )`);
    await c.execute("INSERT INTO migraciones(nombre) VALUES ('009_recuperaciones')");
    await c.commit();
    console.log("Seguimiento de créditos, reembolsos y pérdidas preparado.");
  } catch (e) { await c.rollback(); throw e; }
  finally { await c.close(); await driver.cerrarPool(); }
}
main().catch((e) => { console.error(e.message); process.exitCode = 1; });
