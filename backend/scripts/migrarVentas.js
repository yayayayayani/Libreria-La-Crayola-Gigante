require("dotenv").config({ quiet: true });
const driver = require("../src/config/driver");
const { conectar, filas } = require("../src/services/db");
async function main() {
  const c = await conectar();
  const pg = driver.motor() === "postgres";
  try {
    if ((await filas(c, "SELECT nombre FROM migraciones WHERE nombre='005_ventas'")).length) return;
    const id = pg
      ? "BIGINT GENERATED BY DEFAULT AS IDENTITY"
      : "NUMBER GENERATED BY DEFAULT AS IDENTITY";
    const num = pg ? "BIGINT" : "NUMBER(10)";
    const str = (n) => (pg ? `VARCHAR(${n})` : `VARCHAR2(${n} CHAR)`);
    const run = async (sql) => {
      try {
        await c.execute(sql);
      } catch (e) {
        if (!(!pg && [955, 1430].includes(e.errorNum))) throw e;
      }
    };
    await run(
      `CREATE TABLE ventas(id_venta ${id} PRIMARY KEY,id_cliente ${num} REFERENCES clientes(id_cliente),id_usuario ${num} NOT NULL REFERENCES usuarios(id_usuario),cliente_nombre ${str(201)} NOT NULL,documento ${str(20)},clave ${str(64)} NOT NULL UNIQUE,total DECIMAL(12,2) NOT NULL CHECK(total>0),fecha TIMESTAMP DEFAULT ${pg ? "LOCALTIMESTAMP" : "SYSTIMESTAMP"} NOT NULL)`,
    );
    await run(
      `CREATE TABLE detalle_ventas(id_detalle ${id} PRIMARY KEY,id_venta ${num} NOT NULL REFERENCES ventas(id_venta),id_producto ${num} NOT NULL REFERENCES productos(id_producto),cantidad ${num} NOT NULL CHECK(cantidad>0),precio DECIMAL(12,2) NOT NULL CHECK(precio>=0),UNIQUE(id_venta,id_producto))`,
    );
    await run(`ALTER TABLE movimientos_inventario ADD id_venta ${num} REFERENCES ventas(id_venta)`);
    const checks = pg
      ? await filas(
          c,
          "SELECT conname nombre,pg_get_constraintdef(oid) definicion FROM pg_constraint WHERE conrelid='movimientos_inventario'::regclass AND contype='c'",
        )
      : await filas(
          c,
          "SELECT constraint_name nombre,search_condition_vc definicion FROM user_constraints WHERE table_name='MOVIMIENTOS_INVENTARIO' AND constraint_type='C'",
        );
    for (const check of checks) {
      if (
        /ENTRADA_COMPRA|stock_nuevo\s*=/i.test(check.DEFINICION) ||
        check.NOMBRE.toLowerCase() === "ck_mov_saldo"
      ) {
        if (!/^[a-zA-Z0-9_]+$/.test(check.NOMBRE))
          throw new Error("Nombre de restricción inesperado");
        await c.execute(`ALTER TABLE movimientos_inventario DROP CONSTRAINT ${check.NOMBRE}`);
      }
    }
    await c.execute(
      "ALTER TABLE movimientos_inventario ADD CONSTRAINT ck_mov_tipo CHECK(tipo IN ('APERTURA','ENTRADA_COMPRA','SALIDA_VENTA'))",
    );
    await c.execute(
      "ALTER TABLE movimientos_inventario ADD CONSTRAINT ck_mov_saldo CHECK(stock_nuevo=stock_anterior+CASE WHEN tipo='SALIDA_VENTA' THEN -cantidad ELSE cantidad END)",
    );
    await c.execute(
      "INSERT INTO permisos(codigo,descripcion) SELECT 'VENTAS_GESTIONAR','Registrar ventas a clientes o consumidor final' " +
        (pg ? "" : "FROM dual ") +
        "WHERE NOT EXISTS (SELECT 1 FROM permisos WHERE codigo='VENTAS_GESTIONAR')",
    );
    await c.execute(
      "INSERT INTO rol_permiso(id_rol,id_permiso) SELECT 1,id_permiso FROM permisos WHERE codigo='VENTAS_GESTIONAR' AND NOT EXISTS (SELECT 1 FROM rol_permiso rp WHERE rp.id_rol=1 AND rp.id_permiso=permisos.id_permiso)",
    );
    await c.execute("INSERT INTO migraciones(nombre) VALUES ('005_ventas')");
    await c.commit();
    console.log("Migración de ventas aplicada.");
  } catch (e) {
    await c.rollback();
    throw e;
  } finally {
    await c.close();
    await driver.cerrarPool();
  }
}
main().catch((e) => {
  console.error(e.message);
  process.exitCode = 1;
});
